// Стандартные сообщения для частых статусов.
// Используются, если сообщение не передали явно: new HttpError(404)
const DEFAULT_MESSAGES = {
    400: 'Некорректный запрос',
    401: 'Требуется авторизация',
    403: 'Доступ запрещён',
    404: 'Ресурс не найден',
    409: 'Конфликт данных',
    500: 'Внутренняя ошибка сервера',
};

/**
 * Ошибка с HTTP-статусом.
 *
 * Обычный Error хранит только сообщение. HttpError дополнительно
 * хранит статус, чтобы глобальный обработчик ошибок знал,
 * какой код вернуть клиенту.
 *
 * Пример: next(new HttpError(404, 'Пользователь не найден'))
 */
export default class HttpError extends Error {
    constructor(status = 500, message = DEFAULT_MESSAGES[status] || 'Ошибка') {
        // super() вызывает все свойства конструктор Error и записывает message
        super(message);
        // Имя класса вместо стандартного "Error" –
        // удобно в логах и для проверки error.name
        this.name = 'HttpError';
        // HTTP-статус, который отправим клиенту
        this.status = status;
        // Убирает конструктор HttpError из стека вызовов,
        // чтобы стек начинался с места, где ошибку создали
        Error.captureStackTrace?.(this, HttpError);
    }
}


// class  Error содержит поля: 
// name	- название типа ошибки
// message	- сообщение об ошибке
// stack	- информация о месте возникновения ошибки и стеке вызовов